/**
 * Known-good QR symbols, module for module.
 *
 * PROVENANCE. Generated once, offline, from `node-qrcode` 1.5.4 — a spec-conformant implementation
 * that is NOT a dependency of this package and never will be, because the whole point of
 * `src/qr.ts` is that the CLI ships no QR library. The call was:
 *
 *   QRCode.create([{ data: text, mode: 'byte' }], { errorCorrectionLevel: 'L' })  → modules.data
 *
 * The mode is FORCED, and that matters: left alone, that library splits a string into the cheapest
 * segments it can find, so "HELLO" comes out as an ALPHANUMERIC symbol and never matches a
 * byte-mode encoder. Byte mode is the right choice for a URL and the only one `src/qr.ts` has.
 *
 * WHY THESE FOUR. Each one exercises something the version below it does not:
 *
 *   hello     v1  — one error block, no alignment pattern, the smallest symbol there is.
 *   site      v2  — an alignment pattern appears.
 *   version8  v8  — the version-information block (v7+) and two error-correction blocks.
 *   stripe    v12 — a 16-bit character count (v10+) and four blocks split across two group sizes,
 *                   at the length and shape of a real Stripe Checkout URL.
 *
 * The mask is chosen by penalty score, so a single wrong bit anywhere upstream — a generator
 * polynomial, an interleave, a reserved module — usually flips the mask and with it every module in
 * the symbol. That makes these comparisons far stricter than their size suggests.
 */

export interface QrFixture {
  readonly name: string;
  readonly text: string;
  readonly version: number;
  readonly size: number;
  /** One string per row, `1` where the module is dark. */
  readonly rows: readonly string[];
}

